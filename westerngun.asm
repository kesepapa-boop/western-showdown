        DEC A
        LD C,A
        LD A,(OX)
        DEC A
        LD B,A
        CALL CALCOFF
        LD DE,MAP
        ADD HL,DE
        LD A,(OH)
        ADD A,2
        LD D,A
        LD A,(OW)
        ADD A,2
        LD E,A
FC1:    CALL VBLTRK
        LD B,E
FC2:    LD A,(HL)
        OR A
        JR NZ,FC_BAD
        INC HL
        DJNZ FC2
        PUSH DE
        LD A,40
        SUB E
        LD E,A
        LD D,0
        ADD HL,DE
        POP DE
        DEC D
        JR NZ,FC1
        OR A
        RET
FC_BAD: SCF
        RET

