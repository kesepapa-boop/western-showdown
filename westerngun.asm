        RET


; ==========================================================================
;  joystick (MSX/Atari type via the MZ-1X03 adapter, original protocol)
;  port 1 : JA1 = E008 bit1, JA2 = bit2   -> left  player
;  port 2 : JB1 = E008 bit3, JB2 = bit4   -> right player
;  A = fire, B = aim change.  Interrupts are disabled all the time (DI).
;  JOYGET : OUT HL = 12 bit control word, same layout as KEYCUR (1 = pressed)
;           a port without a joystick connected is not read (no hang)
; ==========================================================================
JOYGET: LD HL,0
        LD A,JOY
        OR A
        RET Z
        LD DE,0
        CALL CHKJ1
        JR C,JG1
        CALL RJOY1
        CALL JCONV
        LD E,A
JG1:    CALL CHKJ2
        JR C,JG2
        CALL RJOY2
        CALL JCONV
        LD C,A
        RRCA
        RRCA
        AND 0C0H
        OR E
        LD E,A
        LD A,C
        RRCA
        RRCA
        AND 0FH
        LD D,A
JG2:    LD H,D
        LD L,E
        RET

; A = 11UDRLBA (0 = pressed)  ->  A = 00FAlrdu game bits (1 = pressed)
JCONV:  AND 3FH
        LD C,A
        LD B,0
        LD HL,JTAB
        ADD HL,BC
        LD A,(HL)
        RET

; any joystick button/direction pressed ? (title screen) ; Z = none
SCANWK: CALL SCANANY
        RET NZ
        CALL JOYGET
        LD A,H
        OR L
        RET

; connected check : Cy = 0 connected, 1 not.  JA2/JB2 must go Low
CHKJ1:  LD A,04H
        JR CHKJ
CHKJ2:  LD A,10H
CHKJ:   LD B,7
        LD HL,0E008H
CJ1:    AND (HL)
        DJNZ CJ1
        RET Z
        SCF
        RET

; ---- port 1 reader (timing critical, 3.58 MHz T-states in comments) ----
RJOY1:  LD HL,0E008H
        LD BC,0E04H             ; JA2
RJ1A:   LD A,C
        AND (HL)
        JR Z,RJ1A
RJ1B:   AND (HL)
        JR NZ,RJ1B
        LD A,(HL)
        RRCA
        RRCA
        RL B
        LD A,06H
        AND (HL)
        ADD A,B
        AND 33H
        RRCA
        RRCA
        LD B,A
        LD A,(HL)
        AND 06H
        ADD A,B
        RLCA
        RLCA
        LD B,A
        LD A,(HL)
        RLCA
        AND C
        OR B
        OR 0C0H
        LD C,A
        AND 0CH
        LD A,C
        RET NZ
        AND 30H                 ; R and L both 0 : SELECT/RUN code, no direction
        DEC A
        ADD A,A
        ADD A,A
        OR B
        RET

; ---- port 2 reader ----
RJOY2:  LD HL,0E008H
        LD C,10H                ; JB2
RJ2A:   LD A,C
        AND (HL)
        JR Z,RJ2A
RJ2B:   AND (HL)
        JR NZ,RJ2B
        LD A,(HL)
        AND L
        OR H
        RRCA
        LD B,A
        LD A,18H
        AND (HL)
        ADD A,B
        AND 0CCH
        RRCA
        LD B,A
        NOP
        LD A,(HL)
        AND 18H
        RLCA
        ADD A,B
        RRCA
        LD B,A
        LD A,(HL)
        AND L
        RRCA
        OR B
        OR 0C0H
        LD C,A
        AND 0CH
        LD A,C
        RET NZ
        AND 30H
        DEC A
        ADD A,A
        ADD A,A
        OR B
        RET

JTAB:
        DB 3FH,1FH,2FH,0FH,3BH,1BH,2BH,0BH
        DB 37H,17H,27H,07H,33H,13H,23H,03H
        DB 3DH,1DH,2DH,0DH,39H,19H,29H,09H
        DB 35H,15H,25H,05H,31H,11H,21H,01H
        DB 3EH,1EH,2EH,0EH,3AH,1AH,2AH,0AH
        DB 36H,16H,26H,06H,32H,12H,22H,02H
        DB 3CH,1CH,2CH,0CH,38H,18H,28H,08H
        DB 34H,14H,24H,04H,30H,10H,20H,00H

; ==========================================================================
;  timing : wait for one video frame (works whichever polarity bit 7 has)
; ==========================================================================
WAITVBL: CALL WAITV0
        LD A,1
        LD (LASTVB),A
        JP SNDTICK

; look at the blanking bit; every new frame seen is counted in LOSTF.  called from the
; long jobs (REFRESH, obstacle generation) so that no frame is lost to the game clock.
VBLTRK: PUSH AF
        PUSH HL
        LD A,(PPI_C)
        RLCA
        LD A,(LASTVB)
        JR C,VT1
        XOR A
        LD (LASTVB),A
        JR VT9
VT1:    OR A
        LD A,1
        LD (LASTVB),A
        JR NZ,VT9
        LD HL,LOSTF
        INC (HL)
VT9:    POP HL
        POP AF
        RET
WAITV0: LD HL,0
WV1:    LD A,(PPI_C)
        RLCA
        JR NC,WV2
        DEC HL
        LD A,H
        OR L
        JR NZ,WV1
        RET
WV2:    LD HL,0
WV3:    LD A,(PPI_C)
        RLCA
        JR C,WV4
        DEC HL
        LD A,H
        OR L
        JR NZ,WV3
WV4:    RET

; ==========================================================================
;  sound  (8253 counter 0, square wave; frequency = 894886 / count)
;  a sound is a list of notes : DW count, DB frames   ended by DW 0
; ==========================================================================
; HL = sound list, A = priority.  a running sound of higher priority is not interrupted
SNDPLAY: PUSH BC
        PUSH DE
        PUSH HL
        LD B,A
        LD A,SOUND
        OR A
        JR Z,SP9
        LD A,(DEMOF)
        OR A
        JR NZ,SP9               ; the demo is silent
        LD A,(SNDACT)
        OR A
        JR Z,SP1
        LD A,(SNDPRI)
        CP B
        JR C,SP1
        JR Z,SP1
        JR SP9
SP1:    LD A,B
        LD (SNDPRI),A
        LD (SNDPTR),HL
        LD A,1
        LD (SNDACT),A
        XOR A
        LD (SNDCNT),A
        CALL SNDTICK
SP9:    POP HL
        POP DE
        POP BC
        RET

; called once per frame
SNDTICK: LD A,(SNDACT)
        OR A
        RET Z
        LD A,(SNDCNT)
        OR A
        JR NZ,SK_DEC
        LD HL,(SNDPTR)
        LD E,(HL)
        INC HL
        LD D,(HL)
        INC HL
        LD A,D
        OR E
        JR Z,SK_END
        LD A,(HL)
        INC HL
        LD (SNDPTR),HL
        LD (SNDCNT),A
        LD A,36H
        LD (SND_CTL),A
        LD A,E
        LD (SND_T0),A
        LD A,D
        LD (SND_T0),A
        LD A,1
        LD (SND_GATE),A
SK_DEC: LD HL,SNDCNT
        DEC (HL)
        RET
SK_END: XOR A
        LD (SND_GATE),A
        LD (SNDACT),A
        LD (SNDPRI),A
        RET

