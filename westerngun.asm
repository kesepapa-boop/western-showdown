; ==========================================================================
;  WESTERN GUN  for SHARP MZ-700 + PCG-700      (Z80 machine code)
;  2 players, 90 seconds, load/exec address 1200H
; --------------------------------------------------------------------------
;  Left  player : W/X/A/S = up/down/left/right, F = aim change, G = fire
;  Right player : cursor keys, : = aim change, ; = fire        (defaults, table KEYDEF)
;  Title screen : a demo (both cowboys are played by the CPU at random) runs behind the
;                  title and the menu, which are always drawn in front of the field.
;  Menu : [1] 2-player game  [2] key configuration (learns all 12 keys)
;         [3] 1-player game : the right cowboy is played by the CPU
; ==========================================================================
;  Build notes
;   - plain Z80 mnemonics, ORG/EQU/DB/DW only.  Assembled with asm80 (a copy in which
;     the symbolic displacements (IX+PST) were replaced by numbers, because asm80
;     cannot evaluate symbols there; Z80AS-style assemblers accept the symbolic form).
;   - the PCG-700 pattern data (PCGDATA) is generated by gen_gfx.py; bit 7 of every
;     pattern byte is the LEFT-most dot.
;   - the key table KEYDEF holds the default keys.  Menu item 2 learns new keys at run
;     time (12 key presses) and shows the learned "strobe,mask" pairs, which can be
;     copied into KEYDEF to make them the new defaults.
; ==========================================================================

; ---------------- user settings ----------------
ROCK_MIN    EQU 7               ; number of rocks      : ROCK_MIN .. ROCK_MAX
ROCK_MAX    EQU 10
CACT_MIN    EQU 3               ; number of cacti      : CACT_MIN .. CACT_MAX
CACT_MAX    EQU 4
JOY         EQU 1               ; 1 = read MSX joysticks via the MZ-1X03 adapter (port1 = left, port2 = right)
SOUND       EQU 1               ; 1 = sound effects on, 0 = off
FRAME_UNITS EQU 10              ; time units per video frame (1 unit = 1/600 s)
                                ;   60Hz machine : 10      50Hz machine : 12
GAME_UNITS  EQU 54000           ; game length   90 s
MOVE_UNITS  EQU 60              ; cowboy move   0.1 s per cell
BUL_UNITS   EQU 15              ; bullet speed  0.025 s per cell (30 = 0.05 s)
FALL_UNITS  EQU 600             ; fall-down time 1 s
FALL_LYING  EQU 480             ; remaining time at which "tilting" changes to "lying"

; ---------------- hardware ----------------
PPI_A       EQU 0E000H          ; 8255 port A : keyboard strobe (output)
PPI_B       EQU 0E001H          ; 8255 port B : keyboard data   (input, active low)
PPI_C       EQU 0E002H          ; 8255 port C : bit7 = vertical blanking signal
SND_T0      EQU 0E004H          ; 8253 counter 0 (sound)
SND_CTL     EQU 0E007H          ; 8253 control word
SND_GATE    EQU 0E008H          ; bit 0 = sound on/off (gate of counter 0)
PCG_D       EQU 0E010H          ; PCG-700 data
PCG_L       EQU 0E011H          ; PCG-700 address low
PCG_H       EQU 0E012H          ; PCG-700 address high + control
VRAM        EQU 0D000H
ATTR        EQU 0D800H

; ---------------- screen geometry ----------------
TOPROW      EQU 2               ; first play-field row (rows 0,1 = score line)
MAXY        EQU 23              ; max top-left Y of a cowboy (2 rows high)
MAXX        EQU 38              ; max top-left X of a cowboy (2 columns wide)
BULTILE     EQU 80H

; ---------------- work area ----------------
MAP         EQU 0C000H          ; obstacle map, 40 x 25 (+ spare), 0C000H-0C4FFH
VARS        EQU 0C500H
SEED        EQU VARS+0
TIME        EQU VARS+2
NEXTBUL     EQU VARS+4
NEXTSEC     EQU VARS+6
SECLEFT     EQU VARS+8
KEYCUR      EQU VARS+9
KEYPREV     EQU VARS+11
KEYEDGE     EQU VARS+13
SCORE0      EQU VARS+15
SCORE1      EQU VARS+16
OSIDE       EQU VARS+17
OW          EQU VARS+18
OH          EQU VARS+19
OBASE       EQU VARS+20
OX          EQU VARS+21
OY          EQU VARS+22
OTRY        EQU VARS+23
OCNT        EQU VARS+24
KSI         EQU VARS+25
SNDACT      EQU VARS+26         ; 1 = a sound is playing
SNDCNT      EQU VARS+27         ; frames left in the current note
SNDPRI      EQU VARS+28         ; priority of the current sound
SNDPTR      EQU VARS+29         ; word : next note
MVTOG       EQU VARS+31         ; toggles the pitch of the footstep sound
RROW        EQU VARS+32         ; next row to bring up to date after a new layout (25 = none)
RCNT        EQU VARS+33
LASTVB      EQU VARS+34         ; last seen state of the vertical blanking bit
LOSTF       EQU VARS+35         ; frames that went by while a long job was running
CPUMODE     EQU VARS+36         ; 0 = two players, 1 = right cowboy is played by the CPU
CPUST       EQU VARS+37         ; 4 bytes : CPU state of each cowboy = (direction bits, frames left)
                                ;   direction bits : 0 up, 1 down, 2 left, 3 right
DEMOF       EQU VARS+3BH        ; 1 = demo running behind the title screen
OVLADD      EQU VARS+3CH        ; offset added to the characters of an overlay text
OVL         EQU MAP+0A00H       ; overlay (title + menu), 40 x 25 : 0 = transparent, 0FFH = blank, else tile
RSAVE       EQU VARS+0D0H       ; 10 bytes : old state of both players
OLDMAP      EQU MAP+0600H       ; copy of the previous layout (0C600H-0C9E7H)
KEYTAB      EQU VARS+40H        ; 12 x (strobe,mask)
P0          EQU VARS+80H        ; left  player (16 bytes)
P1          EQU VARS+90H        ; right player (16 bytes)
LINEBUF     EQU VARS+0A0H

; player structure offsets
PX          EQU 0               ; cowboy X (top-left)
PY          EQU 1               ; cowboy Y (top-left)
PST         EQU 2               ; 0 = alive, 1 = falling(tilt), 2 = lying
PAIM        EQU 3               ; aim step 0..3 (straight,up,straight,down)
PBACT       EQU 4               ; bullet active
PBX         EQU 5
PBY         EQU 6
PBDX        EQU 7
PBDY        EQU 8
PBSTK       EQU 9               ; bullet reflected on previous step
PFEND       EQU 10              ; word : time at which the fall ends
PNMOVE      EQU 12              ; word : time of next allowed move
PFACE       EQU 14              ; 0 = faces right, 1 = faces left
PBASE       EQU 15              ; first PCG tile code of this cowboy

        ORG 1200H

; ==========================================================================
START:  DI
        LD SP,0CFF0H
        LD HL,0ACE1H
        LD (SEED),HL
        LD HL,0
        LD (KEYCUR),HL
        XOR A
        LD (SND_GATE),A
        LD (SNDACT),A
        LD (SNDPRI),A
        LD (MVTOG),A
        CALL PCGINIT
        LD HL,KEYDEF
        LD DE,KEYTAB
        LD BC,24
        LDIR
MENU:   CALL DEMO               ; A = 0 : 2-player game,  1 : key configuration,  2 : 1P game
        LD B,A
        XOR A
        LD (DEMOF),A
        LD HL,(SEED)
        LD A,H
        OR L
        JR NZ,MN1
        LD HL,0ACE1H
        LD (SEED),HL
MN1:    LD A,B
        CP 1
        JR Z,DOCFG
        CP 2
        LD A,0
        JR NZ,MN2
        INC A
MN2:    LD (CPUMODE),A
NEWG:   CALL GAME
        CALL RESULT
        JR MENU
DOCFG:  CALL KEYSETUP
        JR MENU

; ==========================================================================
;  title / result screens
; ==========================================================================
; ==========================================================================
;  title screen = demo.  The game field runs behind the title and the menu with both
;  cowboys played by the CPU.  The title and the menu live in the overlay buffer OVL and
;  are always drawn in front (see RFMAIN).  Returns the menu choice in A.
; ==========================================================================
DEMO:   CALL SCANWK             ; wait until every key / stick button is released
        JR NZ,DEMO
        LD A,1
        LD (DEMOF),A
        CALL OVLBUILD
        CALL CLS
        JP GINIT

; menu poll : A = 0FFH nothing,  0 = [1] / stick,  1 = [2],  2 = [3]
MENUPOLL: LD A,0F5H             ; strobe 5 : [1] = bit 7, [2] = bit 6, [3] = bit 5
        LD (PPI_A),A
        NOP
        NOP
        LD A,(PPI_B)
        CPL
        LD C,A
        BIT 7,C
        LD A,0
        RET NZ
        BIT 6,C
        LD A,1
        RET NZ
        BIT 5,C
        LD A,2
        RET NZ
        CALL JOYGET             ; a joystick button / direction starts a 2-player game
        LD A,H
        OR L
        LD A,0FFH
        RET Z
        XOR A
        RET

; ---- overlay : title and menu
OVLBUILD: LD HL,OVL
        LD DE,OVL+1
        LD BC,999
        LD (HL),0
        LDIR
        LD C,3                  ; blank band behind the title
        CALL OVBAND
        LD C,4
        CALL OVBAND
        LD C,5
        CALL OVBAND
        LD HL,STITLE
        LD B,12
        LD C,4
        CALL OVLASC
        LD HL,SMENU1
        LD B,11
        LD C,18
        CALL OVLASC
        LD HL,SMENU2
        LD B,11
        LD C,20
        CALL OVLASC
        LD HL,SMENU3
        LD B,11
        LD C,22
        JP OVLASC

OVBAND: LD B,10
        CALL CALCOFF
        LD DE,OVL
        ADD HL,DE
        LD B,19
        LD A,0FFH
OVB1:   LD (HL),A
        INC HL
        DJNZ OVB1
        RET

; text (ASCII string) or raw tile codes at (B,C) into the overlay, with a blank cell on
; both sides so that the text can be read over rocks and cowboys
OVLASC: LD A,0A0H
        JR OVL0
OVLRAW: XOR A
OVL0:   LD (OVLADD),A
        PUSH HL
        CALL CALCOFF
        LD DE,OVL
        ADD HL,DE
        EX DE,HL
        POP HL
        DEC DE
        LD A,0FFH
        LD (DE),A
        INC DE
OVL1:   LD A,(HL)
        OR A
        JR Z,OVL2
        INC HL
        PUSH HL
        LD HL,OVLADD
        ADD A,(HL)
        POP HL
        LD (DE),A
        INC DE
        JR OVL1
OVL2:   LD A,0FFH
        LD (DE),A
        RET

RESULT: CALL CLS
        LD HL,S1P
        LD B,13
        LD C,12
        CALL PRINTAT
        LD A,(SCORE0)
        LD B,16
        LD C,12
        CALL DRAWNUM
        LD HL,S2P
        LD B,22
        LD C,12
        CALL PRINTAT
        LD A,(SCORE1)
        LD B,25
        LD C,12
        CALL DRAWNUM
        LD A,(SCORE0)
        LD B,A
        LD A,(SCORE1)
        CP B
        LD HL,SWINL
        JR C,RS1
        LD HL,SWINR
        JR NZ,RS1
        LD HL,SDRAW
RS1:    LD A,(CPUMODE)
        OR A
        JR Z,RS2
        LD DE,SWINR
        OR A
        SBC HL,DE
        ADD HL,DE
        JR NZ,RS2
        LD HL,SCPUW
RS2:    LD B,14
        LD C,9
        CALL PRINTAT
        LD HL,SPRESS
        LD B,13
        LD C,16
        CALL PRINTAT
        JP WAITKEY

; wait until all keys are released, then until any key is pressed.
; the waiting time is used to stir the random number seed
WAITKEY: CALL SCANWK
        JR NZ,WAITKEY
WK1:    LD HL,(SEED)
        INC HL
        LD (SEED),HL
        CALL SCANWK
        JR Z,WK1
        LD HL,(SEED)
        LD A,H
        OR L
        RET NZ
        LD HL,0ACE1H
        LD (SEED),HL
        RET

; ==========================================================================
;  key setup (learn which keyboard matrix position each control uses)
; ==========================================================================
KEYSETUP: XOR A
        LD (KSI),A
KS1:    CALL CLS
        LD HL,SKEYSET
        LD B,15
        LD C,6
        CALL PRINTAT
        LD HL,SPRESSKEY
        LD B,13
        LD C,10
        CALL PRINTAT
        LD A,(KSI)
        ADD A,A
        LD E,A
        LD D,0
        LD HL,KNAMES
        ADD HL,DE
        LD E,(HL)
        INC HL
        LD D,(HL)
        EX DE,HL
        LD B,17
        LD C,12
        CALL PRINTAT
KS2:    CALL SCANANY
        JR NZ,KS2
KS3:    CALL SCANANY
        JR Z,KS3
        PUSH AF
        LD A,(KSI)
        ADD A,A
        LD E,A
        LD D,0
        LD HL,KEYTAB
        ADD HL,DE
        LD (HL),B
        INC HL
        POP AF
        LD (HL),A
KS4:    CALL SCANANY
        JR NZ,KS4
        LD A,(KSI)
        INC A
        LD (KSI),A
        CP 12
        JR NZ,KS1
        ; show the learned table
        CALL CLS
        LD HL,SKEYTBL
        LD B,12
        LD C,5
        CALL PRINTAT
        LD HL,KEYTAB
        LD C,8
        CALL KSLINE
        LD C,10
        CALL KSLINE
        LD HL,SCOPY
        LD B,6
        LD C,13
        CALL PRINTAT
        LD HL,SPRESS
        LD B,13
        LD C,17
        CALL PRINTAT
        JP WAITKEY

KSLINE: LD DE,LINEBUF
        LD B,6
KL1:    LD A,(HL)
        INC HL
        CALL PUTHEX
        LD A,(HL)
        INC HL
        CALL PUTHEX
        LD A,20H
        LD (DE),A
        INC DE
        DJNZ KL1
        XOR A
        LD (DE),A
        PUSH HL
        LD HL,LINEBUF
        LD B,3
        CALL PRINTAT
        POP HL
        RET

PUTHEX: PUSH AF
        RRCA
        RRCA
        RRCA
        RRCA
        CALL PUTNIB
        POP AF
PUTNIB: AND 0FH
        ADD A,48
        CP 58
        JR C,PN1
        ADD A,7
PN1:    LD (DE),A
        INC DE
        RET

; any key pressed ?   out: Z = none ;  NZ = key, B = strobe, A = key mask
SCANANY: LD B,0
SA1:    LD A,B
        OR 0F0H
        LD (PPI_A),A
        NOP
        NOP
        LD A,(PPI_B)
        CPL
        OR A
        JR NZ,SA2
        INC B
        LD A,B
        CP 10
        JR NZ,SA1
        XOR A
        RET
SA2:    LD D,A
        NEG
        AND D
        RET

; ==========================================================================
;  one game
; ==========================================================================
GAME:   XOR A
        LD (DEMOF),A
        CALL CLS
GINIT:  XOR A                   ; (the demo restarts here without clearing the screen)
        LD (CPUST),A
        LD (CPUST+1),A
        LD (CPUST+2),A
        LD (CPUST+3),A
        LD HL,MAP
        LD (HL),0
        LD DE,MAP+1
        LD BC,04FFH
        LDIR
        CALL GENOBJS
        LD HL,P0INIT
        LD DE,P0
        LD BC,32
        LDIR
        XOR A
        LD (SCORE0),A
        LD (SCORE1),A
        LD A,25
        LD (RROW),A
        LD HL,0
        LD (TIME),HL
        LD HL,BUL_UNITS
        LD (NEXTBUL),HL
        LD HL,600
        LD (NEXTSEC),HL
        LD A,90
        LD (SECLEFT),A
        CALL DRAWALL
        LD A,(DEMOF)
        OR A
        CALL Z,DRAWHUD
        CALL READKEYS
        CALL READKEYS
        LD HL,SND_START
        LD A,2
        CALL SNDPLAY
        XOR A
        LD (LOSTF),A

GLOOP:  CALL WAITVBL
        LD A,(LOSTF)
        INC A
        LD B,A
        XOR A
        LD (LOSTF),A
        LD HL,(TIME)
        LD DE,FRAME_UNITS
GL0:    ADD HL,DE
        DJNZ GL0
        LD (TIME),HL
        CALL READKEYS
        LD A,(DEMOF)
        OR A
        JR Z,GL4
        CALL MENUPOLL           ; demo : a menu key ends it
        CP 0FFH
        RET NZ
GL4:    ; ---- left player
        LD A,(KEYCUR)
        AND 3FH
        LD C,A
        LD A,(KEYEDGE)
        AND 3FH
        LD B,A
        LD IX,P0
        LD A,(DEMOF)
        OR A
        CALL NZ,CPUCTL          ; demo : the CPU plays the left cowboy as well
        CALL PLAYER
        ; ---- right player
        LD HL,(KEYCUR)
        CALL SHR6
        LD A,L
        AND 3FH
        LD C,A
        LD HL,(KEYEDGE)
        CALL SHR6
        LD A,L
        AND 3FH
        LD B,A
        LD IX,P1
        LD A,(DEMOF)
        LD E,A
        LD A,(CPUMODE)
        OR E
        CALL NZ,CPUCTL          ; 1-player mode / demo : the CPU decides instead of keys / stick 2
        CALL PLAYER
        ; ---- bullets
        LD HL,(TIME)
        LD DE,(NEXTBUL)
        OR A
        SBC HL,DE
        JR C,GL2
        LD HL,(NEXTBUL)
        LD DE,BUL_UNITS
        ADD HL,DE
        LD (NEXTBUL),HL
        LD IX,P0
        CALL STEPB
        LD IX,P1
        CALL STEPB
GL2:    CALL RFSTEP
        ; ---- remaining seconds
        LD HL,(TIME)
        LD DE,(NEXTSEC)
        OR A
        SBC HL,DE
        JR C,GL3
        LD HL,(NEXTSEC)
        LD DE,600
        ADD HL,DE
        LD (NEXTSEC),HL
        LD A,(SECLEFT)
        DEC A
        LD (SECLEFT),A
        CALL DRAWTIME
GL3:    LD HL,(TIME)
        LD DE,GAME_UNITS
        OR A
        SBC HL,DE
        JP C,GLOOP
        LD A,(DEMOF)
        OR A
        JP NZ,GINIT             ; demo : start again with a new layout
        LD HL,SND_END
        LD A,3
        CALL SNDPLAY
GEND1:  CALL WAITVBL
        LD A,(SNDACT)
        OR A
        JR NZ,GEND1
        RET

;  CPU player (IX = cowboy).  out: C = held bits, B = edge bits
;   - a random direction (any of 16 bit patterns, so it may also stand still or move
;     diagonally) is held for 6..37 frames
;   - it never leaves its own half of the screen (left cowboy x <= 18, right cowboy x >= 20)
;   - fire is pressed on every frame, so a new bullet leaves as soon as the old one is gone
;   - the aim is changed at random (about every 0.5 s)
CPUCTL: LD HL,CPUST
        LD A,(IX+PFACE)
        ADD A,A
        LD E,A
        LD D,0
        ADD HL,DE               ; HL -> direction byte of this cowboy
        INC HL
        LD A,(HL)               ; frames left
        OR A
        JR NZ,CC1
        CALL RND8
        AND 0FH
        DEC HL
        LD (HL),A
        INC HL
        CALL RND8
        AND 1FH
        ADD A,6
        JR CC2
CC1:    DEC A
CC2:    LD (HL),A
        DEC HL
        LD C,(HL)               ; held direction bits
        LD A,(IX+PFACE)
        OR A
        LD A,(IX+PX)
        JR NZ,CC4
        CP 18
        JR C,CC3
        RES 3,C                 ; left cowboy : no steps to the right of the middle
        JR CC3
CC4:    CP 21
        JR NC,CC3
        RES 2,C                 ; right cowboy : no steps to the left of the middle
CC3:    LD B,20H                ; fire
        CALL RND8
        CP 8
        RET NC
        SET 4,B                 ; aim change
        RET

SHR6:   LD B,6
S61:    SRL H
        RR L
        DJNZ S61
        RET

; ==========================================================================
;  player handling     IX = player, B = edge bits, C = held bits
;  bits : 0 up, 1 down, 2 left, 3 right, 4 aim change, 5 fire
; ==========================================================================
PLAYER: LD A,(IX+PST)
        OR A
        JP NZ,PFALL
        BIT 4,B
        JR Z,PL1
        LD A,(IX+PAIM)
        INC A
        AND 3
        LD (IX+PAIM),A
        CALL REFSELF
PL1:    BIT 5,B
        JR Z,PL2
        LD A,(IX+PBACT)
        OR A
        CALL Z,FIRE
PL2:    LD A,C
        AND 0FH
        RET Z
        LD HL,(TIME)
        LD E,(IX+PNMOVE)
        LD D,(IX+PNMOVE+1)
        OR A
        SBC HL,DE
        RET C
        LD D,(IX+PX)
        LD E,(IX+PY)
        LD B,0                  ; B = number of axes that moved
        BIT 0,C                 ; vertical axis (up has priority over down)
        JR Z,PM1
        LD A,E
        CP TOPROW
        JR Z,PM2
        DEC (IX+PY)
        INC B
        JR PM2
PM1:    BIT 1,C
        JR Z,PM2
        LD A,E
        CP MAXY
        JR NC,PM2
        INC (IX+PY)
        INC B
PM2:    BIT 2,C                 ; horizontal axis (left has priority over right)
        JR Z,PM3
        LD A,D
        OR A
        JR Z,PM4
        DEC (IX+PX)
        INC B
        JR PM4
PM3:    BIT 3,C
        JR Z,PM4
        LD A,D
        CP MAXX
        JR NC,PM4
        INC (IX+PX)
        INC B
PM4:    LD A,B
        OR A
        RET Z                   ; nothing could move
PMOV:   LD HL,(TIME)
        LD BC,MOVE_UNITS
        ADD HL,BC
        LD (IX+PNMOVE),L
        LD (IX+PNMOVE+1),H
        LD A,(MVTOG)
        XOR 1
        LD (MVTOG),A
        LD HL,SND_MOVE1
        JR Z,PM_S
        LD HL,SND_MOVE2
PM_S:   XOR A
        CALL SNDPLAY
        LD B,D
        LD C,E
        CALL REFBOX
        JP REFSELF

; ---- falling / lying cowboy
PFALL:  LD L,(IX+PFEND)
        LD H,(IX+PFEND+1)
        LD DE,(TIME)
        OR A
        SBC HL,DE
        JR C,PRESP
        LD A,H
        OR L
        JR Z,PRESP
        LD A,(IX+PST)
        CP 1
        RET NZ
        LD DE,FALL_LYING+1
        OR A
        SBC HL,DE
        RET NC
        LD (IX+PST),2
        JP REFSELF
PRESP:  JP NEWROUND

; ---- a fallen cowboy gets up : both cowboys go back to their start positions and a
;      new random layout of rocks and cacti is made.  the game time keeps running; the
;      screen is brought up to date a few rows per frame (see RFSTEP).
NEWROUND: LD IX,P0
        LD HL,RSAVE
        CALL RSAVEP
        LD IX,P1
        CALL RSAVEP
        CALL CPYMAP
        CALL CLRMAP
        CALL GENOBJS
        LD A,TOPROW
        LD (RROW),A
        LD IX,P0
        LD HL,RSAVE
        CALL RREFP
        LD IX,P1
        LD HL,RSAVE+5
        JP RREFP

; MAP -> OLDMAP and MAP := 0, in small pieces so that VBLTRK can watch the screen
CPYMAP: LD HL,MAP
        LD DE,OLDMAP
        LD A,10
CM1:    LD BC,100
        LDIR
        PUSH AF
        CALL VBLTRK
        POP AF
        DEC A
        JR NZ,CM1
        RET
CLRMAP: LD HL,MAP
        LD A,10
CL1:    LD (HL),0
        LD D,H
        LD E,L
        INC DE
        LD BC,127
        LDIR
        INC HL
        PUSH AF
        CALL VBLTRK
        POP AF
        DEC A
        JR NZ,CL1
        RET

; save X,Y,bullet(active,X,Y) of player IX at (HL), then put the player back
RSAVEP: LD A,(IX+PX)
        LD (HL),A
        INC HL
        LD A,(IX+PY)
        LD (HL),A
        INC HL
        LD A,(IX+PBACT)
        LD (HL),A
        INC HL
        LD A,(IX+PBX)
        LD (HL),A
        INC HL
        LD A,(IX+PBY)
        LD (HL),A
        INC HL
        LD A,(IX+PFACE)
        OR A
        LD A,1
        JR Z,RP1
        LD A,37
RP1:    LD (IX+PX),A
        LD A,12
        LD (IX+PY),A
        XOR A
        LD (IX+PST),A
        LD (IX+PAIM),A
        LD (IX+PBACT),A
        LD (IX+PNMOVE),A
        LD (IX+PNMOVE+1),A
        RET

; redraw the old cowboy box, the old bullet cell and the new cowboy box of player IX
RREFP:  LD B,(HL)
        INC HL
        LD C,(HL)
        INC HL
        LD A,(HL)
        INC HL
        PUSH AF
        LD D,(HL)
        INC HL
        LD E,(HL)
        POP AF
        PUSH DE
        CALL REFBOX
        POP DE
        OR A
        JR Z,RR1
        LD B,D
        LD C,E
        CALL REFRESH
RR1:    JP REFSELF

; every frame : redraw 4 rows of the cells whose map code changed
RFSTEP: LD A,4
        LD (RCNT),A
RFS1:    LD A,(RROW)
