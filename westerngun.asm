        LD C,A
        LD A,(OX)
        LD B,A
        CALL CALCOFF
        LD DE,MAP
        ADD HL,DE
        LD A,(OH)
        LD D,A
        LD A,(OBASE)
        LD E,A
ST1:    LD A,(OW)
        LD B,A
        PUSH HL
ST2:    LD (HL),E
        INC HL
        INC E
        DJNZ ST2
        POP HL
        PUSH DE
        LD DE,40
        ADD HL,DE
        POP DE
        DEC D
        JR NZ,ST1
        RET

