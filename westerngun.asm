; ==========================================================================
;  keyboard : builds KEYCUR (12 bits) / KEYEDGE (newly pressed)
;  bit 0-5  left  player : up, down, left, right, aim, fire
;  bit 6-11 right player : up, down, left, right, aim, fire
; ==========================================================================
READKEYS: LD HL,(KEYCUR)
        LD (KEYPREV),HL
        LD HL,KEYTAB
        LD DE,0
        LD B,12
RK1:    LD A,(HL)
        INC HL
        LD C,(HL)
        INC HL
        OR 0F0H
        LD (PPI_A),A
        NOP
        NOP
        LD A,(PPI_B)
        CPL
        AND C
        SRL D
        RR E
        OR A
        JR Z,RK2
        SET 3,D
RK2:    DJNZ RK1
        PUSH DE
        CALL JOYGET
        POP DE
        LD A,E
        OR L
        LD E,A
        LD A,D
        OR H
        LD D,A
        LD (KEYCUR),DE
        LD HL,(KEYPREV)
        LD A,L
        CPL
        AND E
        LD L,A
        LD A,H
        CPL
        AND D
