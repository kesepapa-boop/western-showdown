        POP DE
        POP BC
        RET

; ==========================================================================
;  obstacle generation
;  rocks (3x2, map codes 20H-25H) and cacti (2x3, map codes 10H-15H) are placed
;  alternately on the left / right half so the two sides differ by at most one.
; ==========================================================================
GENOBJS: XOR A
        LD (OSIDE),A
        LD A,ROCK_MAX-ROCK_MIN+1
        CALL RANDN
        ADD A,ROCK_MIN
        LD (OCNT),A
        LD A,3
        LD (OW),A
        LD A,2
        LD (OH),A
        LD A,20H
        LD (OBASE),A
        CALL PLACEN
        LD A,CACT_MAX-CACT_MIN+1
        CALL RANDN
        ADD A,CACT_MIN
        LD (OCNT),A
        LD A,2
        LD (OW),A
        LD A,3
        LD (OH),A
        LD A,10H
        LD (OBASE),A
PLACEN: LD A,(OCNT)
        OR A
        RET Z
        DEC A
        LD (OCNT),A
        CALL PLACEOBJ
        LD A,(OSIDE)
        XOR 1
        LD (OSIDE),A
        JR PLACEN

; try to place one object (size OW x OH, first code OBASE) on side OSIDE
PLACEOBJ: LD A,100
        LD (OTRY),A
